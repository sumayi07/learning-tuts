# APIs are interfaces that allow interactions between an enterprise and an application that uses it's assets.
# In other words, an API is what allows two software applications to communicate and share data with each other

# HTTP is a protocol of sharing data that is commonly used by APIs.
# It is a client-server protocol. The client (a browser) opens a connection with the server (a web server) and requests data.
# The server then returns the data that is requested and closes the connection.
# The client can make four different types of data requests. GET (used to read data), POST (used to create data). PUT (used to update data), DELETE (used to delete data)